import SwiftUI

/// Вариант рефлекса крупных обложек (`CoverHolo`) — переключатель дебаг-меню для сравнения
/// на устройстве (исследование 2026-11-04 после фидбека «не выглядит натурально: полоска
/// рефлекса должна меняться от наклона, и её угол тоже»). Разведены по характеру — первые
/// три варианта на устройстве читались одинаково («почти не вижу разницы»). Хранится
/// в `UserDefaults` и переживает перезапуск. Названия — рабочие.
enum CoverSheenStyle: String, CaseIterable, Identifiable {
    /// Мягкая полоса поперёк направления на свет: свет закреплён в мире, угол полосы — угол
    /// его проекции на экран (поворот в плоскости экрана — 1:1, наклон — ~0.85° на градус),
    /// положение — от высоты света. Стилизация по образцу карты Telegram Wallet.
    case stripe
    /// Физика: попиксельное отражение круглой лампы, закреплённой в мире, — тонкая заметная
    /// дуга со скоростью настоящего глянца (обложка за ~10° наклона). Угол от поворота
    /// в плоскости — 1:1, от наклона — из-за кривизны.
    case lamp
    /// Широкая мягкая полоса перламутра: тонкая плёнка неровной толщины окрашивает блик,
    /// оттенок плывёт от угла падения, поперёк полосы и по мере её хода.
    case pearl
    /// Лицо обложки чистое, свет ловит только кромка — стороной к свету, как у бликов
    /// Liquid Glass; бежит по краю при наклоне и повороте.
    case edge

    static let storageKey = "coverSheenStyle"
    static let defaultStyle: CoverSheenStyle = .stripe

    var id: Self { self }

    var title: String {
        switch self {
        case .stripe: "Полоса за светом"
        case .lamp: "Кольцевая лампа"
        case .pearl: "Перламутр"
        case .edge: "Блик по кромке"
        }
    }

    /// Номер варианта для шейдера (`CoverHolo.metal`).
    var shaderIndex: Double {
        switch self {
        case .stripe: 0
        case .lamp: 1
        case .pearl: 2
        case .edge: 3
        }
    }
}
