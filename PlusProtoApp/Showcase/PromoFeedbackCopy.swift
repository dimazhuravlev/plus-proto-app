import Foundation

/// Перенос естественный: короткие фразы занимают одну строку, длинные — до двух.
/// Реакция влияет на рекомендации, поэтому тексты не обещают сохранение в коллекцию.
enum PromoFeedbackCopy {
    static let likes = [
        "Учтём оценку в рекомендациях",
        "Будем советовать больше такого",
        "Покажем больше похожего",
        "Учли ваш вкус для рекомендаций",
        "Теперь будем чаще предлагать такое",
        "Запомнили: вам нравится такое",
        "Подберём больше похожего для вас",
        "Таких рекомендаций будет больше",
        "Учли: такого хочется больше",
        "Будем чаще советовать похожее",
    ]
    static let dislikes = [
        "Будем показывать меньше такого",
        "Станем реже советовать такое",
        "Покажем меньше похожего",
        "Учли: такого будет меньше",
        "Будем реже предлагать похожее",
        "Таких рекомендаций станет меньше",
        "Запомнили: такое советуем реже",
        "Учтём оценку: реже предложим похожее",
        "В рекомендациях будет меньше такого",
        "Похожее будем показывать реже",
    ]

    static func liked() -> String { likes.randomElement() ?? likes[0] }
    static func disliked() -> String { dislikes.randomElement() ?? dislikes[0] }
}
