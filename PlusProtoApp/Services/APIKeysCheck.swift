import Foundation

/// Вписаны ли ключи внешних API.
///
/// `APIKeys.swift` лежит в гитигноре, и у нового участника он появляется копией
/// шаблона `APIKeys.example.swift`, где строки пустые. Пустой ключ — не повод
/// показывать пустой экран: витрина в этом случае идёт на моках, как под
/// `-debugMockFeed`, и прототип можно листать сразу после клона. Живые данные
/// включаются сами, едва ключ вписан, — перезапуска приложения достаточно.
enum APIKeysCheck {
    /// Кино — костяк витрины: без Кинопоиска нет ни подборок, ни «продолжить
    /// смотреть», ни чипа киноплеера. Google Books отдельно не проверяем: книжные
    /// метаданные — один блок, и ради него всю ленту на моки переводить незачем
    /// (обложки книг идут с CDN вообще без ключа).
    static var isKinopoiskConfigured: Bool {
        APIKeys.kinopoisk.contains { !$0.trimmingCharacters(in: .whitespaces).isEmpty }
    }
}
