import SwiftUI

/// Затемнение и размытие экрана под активным поиском.
enum SearchOverlayConfig {
    /// Радиус backdrop-блюра в тех же CSS-единицах, что и остальные блюры проекта
    /// (стекло 35, кнопки 20). Экран уходит из фокуса целиком: это не «шторка»,
    /// а расфокус — пользователь помнит, откуда вызвал поиск.
    /// Сильнее прежних 56, но не «в кашу»: на 160 от экрана не оставалось ничего
    /// узнаваемого, и слой читался глухой шторкой (замер: детализация 0.11 против
    /// 8.8 без слоя).
    static let blur: CGFloat = 80
    /// Затемнение поверх блюра — **вот единственная ручка прозрачности** слоя.
    /// Гасить сам слой через `.opacity` нельзя: при непрозрачности меньше единицы
    /// SwiftUI уводит поддерево в отдельный слой, а backdrop-эффекту нужно композиться
    /// прямо с контентом под ним — блюр от этого пропадает целиком, остаётся одно
    /// затемнение (проверено: детализация под слоем 1.77 вместо 0.11).
    static let dim: Double = 0.4
    /// Одна кривая на появление и на исчезновение.
    ///
    /// Клавиатурная не годится, хотя слой и ехал по ней: у показа и у скрытия она
    /// **разной длительности**, и слой уезжал заметно быстрее, чем приезжал. Симметрия
    /// здесь важнее совпадения с клавиатурой до миллисекунды — 0.3 против её ~0.25
    /// на глаз не расходится.
    static let fade: Animation = .easeInOut(duration: 0.3)
    /// Сколько слой держит радиус после того, как начал гаснуть. Больше длительности
    /// самого гашения: снять эффект раньше времени — значит показать резкий кадр
    /// из-под ещё видимого затемнения.
    static let holdAfterHide: Double = 0.4
}

/// Слой поиска над текущим экраном.
///
/// Поиск — **не отдельный экран**: навигация никуда не переходит, нижележащий экран
/// остаётся на месте и просто уходит из фокуса. Поэтому это оверлей в корне, а не пуш
/// в `NavigationStack` — иначе таб потерял бы свой путь, а возврат из поиска читался бы
/// как «назад», а не как «закрыть».
///
/// Сюда же поверх ляжет будущая поисковая выдача: у неё та же система координат
/// и тот же жизненный цикл, что у этого слоя.
struct SearchOverlay: View {
    let isActive: Bool
    /// Тап по затемнению закрывает поиск. Иначе слой ловил бы касания и не делал ничего.
    var onDismiss: () -> Void

    /// Радиус живёт **своей** жизнью, а не выводится из `isActive` прямо в теле.
    ///
    /// Разгонять сам радиус не получается: `Animatable`-обёртка вокруг
    /// `UIViewRepresentable` его не интерполирует. Замер по записи (30 к/с) —
    /// детализация под слоем падает с 17.9 до 1.2 **за один кадр**, и одинаково
    /// что на радиусе 160, что на 40. То есть виден блюр самого материала
    /// `UIVisualEffectView`, а не наш гауссиан, и никакой рампы там нет.
    ///
    /// Поэтому плавность везёт прозрачность — её SwiftUI анимирует честно, — а радиус
    /// просто стоит полным всё время, пока слой виден, и обнуляется уже после того,
    /// как слой стал прозрачным. Обнулять его раньше нельзя: на нуле
    /// `BackdropBlurView` снимает эффект целиком, и под ещё видимым затемнением
    /// мигнул бы резкий экран.
    @State private var radius: CGFloat = 0

    var body: some View {
        ZStack {
            BackdropBlurView(radius: radius)
            Rectangle()
                .fill(.black)
                .opacity(SearchOverlayConfig.dim)
        }
        // В покое ровно 1 — иначе блюр не работает (см. `dim`). Ноль на другом конце
        // безопасен: там слоя и не должно быть видно.
        .opacity(isActive ? 1 : 0)
        .animation(SearchOverlayConfig.fade, value: isActive)
        .ignoresSafeArea()
        .contentShape(.rect)
        .onTapGesture(perform: onDismiss)
        // Порядок критичен и стоит последним осознанно: `allowsHitTesting` гасит
        // только то, что оборачивает. Когда он стоял ДО `contentShape`/`onTapGesture`,
        // жест оказывался снаружи погашенного поддерева и слой ловил касания всегда —
        // невидимый ловец на весь экран поверх всего контента. Тап по карточке витрины
        // уходил в него, и не работали ни переход на экран сущности, ни открытие плеера.
        // Хром лежит выше слоя, поэтому таббар продолжал работать — и это сбивало с толку.
        .allowsHitTesting(isActive)
        .task(id: isActive) {
            guard !isActive else {
                radius = SearchOverlayConfig.blur
                return
            }
            try? await Task.sleep(for: .seconds(SearchOverlayConfig.holdAfterHide))
            guard !Task.isCancelled else { return }
            radius = 0
        }
    }
}
