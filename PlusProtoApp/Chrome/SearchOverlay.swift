import SwiftUI

/// Затемнение и размытие экрана под активным поиском.
enum SearchOverlayConfig {
    /// Радиус backdrop-блюра в тех же CSS-единицах, что и остальные блюры проекта
    /// (стекло 35, кнопки 20). Экран должен уйти из фокуса целиком, но остаться узнаваемым —
    /// это не «шторка», а расфокус: пользователь помнит, откуда вызвал поиск.
    static let blur: CGFloat = 56
    /// Затемнение поверх блюра. Без него размытая витрина остаётся яркой и спорит
    /// с полем ввода за внимание.
    static let dim: Double = 0.68
}

/// Слой поиска над текущим экраном.
///
/// Поиск — **не отдельный экран**: навигация никуда не переходит, нижележащий экран
/// остаётся на месте и просто уходит из фокуса. Поэтому это оверлей в корне, а не пуш
/// в `NavigationStack` — иначе таб потерял бы свой путь, а возврат из поиска читался бы
/// как «назад», а не как «закрыть».
///
/// Сюда же поверх ляжет будущая поисковая выдача: у неё та же система координат
/// и тот же жизненный цикл, что у этого слоя.
struct SearchOverlay: View {
    let isActive: Bool
    /// Кривая текущего движения клавиатуры — та же, что везёт бар (`ActionBarRaise.motion`).
    /// `nil` — клавиатура стоит, и слой едет собственным морфом.
    var motion: Animation?
    /// Тап по затемнению закрывает поиск. Иначе слой ловил бы касания и не делал ничего.
    var onDismiss: () -> Void

    var body: some View {
        ZStack {
            // Радиус едет от нуля, а не проявляется кроссфейдом: при кроссфейде
            // в кадре одновременно видны резкая и размытая копии экрана, и переход
            // читается как двоение.
            AnimatableBackdropBlur(radius: isActive ? SearchOverlayConfig.blur : 0)
            Color.black.opacity(isActive ? SearchOverlayConfig.dim : 0)
        }
        .ignoresSafeArea()
        .contentShape(.rect)
        .onTapGesture(perform: onDismiss)
        // Порядок критичен и стоит последним осознанно: `allowsHitTesting` гасит
        // только то, что оборачивает. Когда он стоял ДО `contentShape`/`onTapGesture`,
        // жест оказывался снаружи погашенного поддерева и слой ловил касания всегда —
        // невидимый ловец на весь экран поверх всего контента. Тап по карточке витрины
        // уходил в него, и не работали ни переход на экран сущности, ни открытие плеера.
        // Хром лежит выше слоя, поэтому таббар продолжал работать — и это сбивало с толку.
        .allowsHitTesting(isActive)
        // Кривая клавиатуры, а не собственная: слой закрывает экран ровно на то время,
        // пока клавиатура на нём. Со своим `.smooth(0.32)` он отставал — клавиатура
        // уже ушла, а размытие ещё держалось, и это читалось как подвисание.
        // `.smooth` остаётся запасным вариантом для случаев, когда движение начинает
        // не клавиатура (тап по затемнению снимает фокус раньше её нотификации).
        .animation(motion ?? ActionBarMotion.morph, value: isActive)
    }
}

/// `UIViewRepresentable` сам по себе не анимируется — SwiftUI не переспрашивает его
/// на промежуточных кадрах. `Animatable` на обёртке заставляет пересобирать `body`
/// с интерполированным радиусом, и блюр разгоняется по-настоящему.
private struct AnimatableBackdropBlur: View, Animatable {
    var radius: CGFloat

    var animatableData: CGFloat {
        get { radius }
        set { radius = newValue }
    }

    var body: some View {
        BackdropBlurView(radius: radius)
    }
}
