// Шаблон секретов. Скопировать в PlusProtoApp/APIKeys.swift — там файл в гитигноре
// и в репозиторий не попадёт:
//
//     cp APIKeys.example.swift PlusProtoApp/APIKeys.swift
//
// Пустые строки — рабочее состояние, а не заглушка «до первого запуска»: проект
// собирается, витрина идёт на моках, вёрстку и анимации видно целиком. Живые данные
// включаются сами, едва вписан ключ Кинопоиска, — достаточно перезапустить приложение.
//
// Сам этот файл в сборку не входит: в таргет синхронизирована папка PlusProtoApp,
// корень репозитория — нет. Поэтому два `enum APIKeys` рядом друг другу не мешают.

import Foundation

enum APIKeys {
    /// kinopoisk.dev — кино: витрина, поиск, карточки тайтлов. Заголовок X-API-KEY.
    /// Бесплатный ключ выдаёт телеграм-бот с https://kinopoisk.dev — минута дела.
    ///
    /// Список, а не строка: квота 200 запросов в сутки считается на ключ, и получив
    /// 403, `KinopoiskService` переключается на следующий.
    /// Одного ключа хватает на день спокойной работы, второй — запас на прогоны.
    static let kinopoisk = [
        "",
    ]

    /// kinopoiskapiunofficial.tech — запас поиска фильмов, когда у kinopoisk.dev кончилась
    /// квота на всех ключах (`KinopoiskUnofficialService`). Заголовок X-API-KEY.
    /// Ключ — после регистрации на https://kinopoiskapiunofficial.tech, в профиле.
    /// Квота своя, 500 запросов в сутки на ключ. Пусто — запаса нет, поиск как раньше.
    /// Вписать ключи во все копии этого файла — `./scripts/set-unofficial-keys.sh`.
    static let kinopoiskUnofficial: [String] = [
        "",
    ]

    /// Google Books — метаданные книг (параметр запроса key). Обложки идут с Google CDN
    /// без ключа, текст — с Викитеки, тоже без ключа: этот ключ нужен только описаниям.
    ///
    /// Где взять: console.cloud.google.com → новый проект → APIs & Services → Library →
    /// включить «Books API» → Credentials → Create credentials → API key. Квота ~1000/сутки.
    /// Оставить пустым можно: книжный блок витрины останется моковым, остальное живое.
    static let googleBooks = ""
}
